#!/usr/bin/env python3
"""Generate a separate fixed-shape array suite without changing the main suite."""

import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--out", type=Path, required=True)
args = parser.parse_args()
args.out.mkdir(parents=True, exist_ok=True)

cases = []
methods = []
configure = []


def add(name, value=None, setup=""):
    index = len(cases)
    spec = {"name": name, "index": index,
            "family": "control" if value is None else "candidx",
            "method": f"bench_{index}"}
    expressions = [(spec["method"], '""' if value is None else
                    f"Prim.to_candid_canonical({value})")]
    if value is not None:
        spec["ordinary_method"] = f"ordinary_{index}"
        expressions.append((spec["ordinary_method"], f"to_candid({value})"))
    for method, expression in expressions:
        methods.append(f"""
  public func {method}() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let started = Prim.performanceCounter(0);
    output := {expression};
    let ended = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = ended - started;
       allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore;
       outputSize = output.size() }}
  }};
""")
    configure.append(f"      case {index} {{ {setup} }};")
    cases.append(spec)


add("control")
for count in [0, 1, 1024]:
    add(f"candid-fixed-records-{count}", "fixed", f"""
      fixed := Prim.Array_tabulate<Fixed>({count}, func(i) {{
        {{ id = Prim.natToNat64(i * 17); signed = -17;
           flag = i % 2 == 0; real = 1.25 }}
      }});
    """)
    add(f"candid-text-records-{count}", "texts", f"""
      texts := Prim.Array_tabulate<WithText>({count}, func(i) {{
        {{ id = Prim.natToNat64(i * 17); text = switch (i % 3) {{
          case 0 ""; case 1 "hello 🌐"; case _ "abcdefghijklmnopqrstuvwxyz"
        }} }}
      }});
    """)

for label, count, inner in [("0", 0, "0"), ("1-empty", 1, "0"),
                            ("1-full", 1, "32"), ("1024-mixed", 1024,
                            "if (i % 3 == 0) 0 else 32")]:
    add(f"candid-blob-records-{label}", "blobs", f"""
      blobs := Prim.Array_tabulate<WithBlob>({count}, func(i) {{
        {{ id = Prim.natToNat64(i * 17); bytes = makeBlob({inner}) }}
      }});
    """)
    add(f"candid-nat8-records-{label}", "octets", f"""
      octets := Prim.Array_tabulate<WithNat8>({count}, func(i) {{
        {{ id = Prim.natToNat64(i * 17); bytes = makeNat8({inner}) }}
      }});
    """)

source = f"""// Generated by test/compute-plugins/bench/generate-static-arrays.py.
import Prim "mo:⛔";
actor {{
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  type Fixed = {{ id : Nat64; signed : Int32; flag : Bool; real : Float }};
  type WithText = {{ id : Nat64; text : Text }};
  type WithBlob = {{ id : Nat64; bytes : Blob }};
  type WithNat8 = {{ id : Nat64; bytes : [Nat8] }};
  transient var fixed : [Fixed] = [];
  transient var texts : [WithText] = [];
  transient var blobs : [WithBlob] = [];
  transient var octets : [WithNat8] = [];
  transient var output : Blob = "";
  func makeNat8(size : Nat) : [Nat8] {{
    Prim.Array_tabulate<Nat8>(size, func(i) {{ Prim.natToNat8((i * 17 + 11) % 256) }})
  }};
  func makeBlob(size : Nat) : Blob {{ Prim.arrayToBlob(makeNat8(size)) }};
  public func configure(index : Nat) : async () {{
    fixed := []; texts := []; blobs := []; octets := []; output := "";
    switch index {{
{chr(10).join(configure)}
      case _ Prim.trap("unknown benchmark")
    }}
  }};
  public func clear() : async () {{ output := "" }};
  public query func bytesResult() : async Blob {{ output }};
  {chr(10).join(methods)}
}}
"""
(args.out / "main.mo").write_text(source)
(args.out / "cases.json").write_text(json.dumps({"suite": "static-arrays",
    "variant_width": 0, "variant_payload": "none", "cases": cases}, indent=2) + "\n")
print(args.out / "main.mo")
